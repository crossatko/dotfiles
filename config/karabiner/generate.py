#!/usr/bin/env python3
"""Generate karabiner.json (stdlib only). Run: python3 -I config/karabiner/generate.py
`--aerospace` prints the matching [mode.main.binding] lines for ../aerospace/aerospace.toml (Skyland).

Design: left Option = Hyprland SUPER, right Command = Hyprland ALT. No modifier is rewritten; every
manipulator matches the PHYSICAL modifiers (side-specific mandatory names) and emits one unique combo
per Hyprland modifier class, which aerospace.toml binds.
"""
import json, os, sys

# Hyprland class -> (physical mandatory modifiers, emitted modifiers, AeroSpace prefix)
CLASSES = {
    "SUPER":           (["left_option"],                               ["left_command", "left_control", "left_option"], "cmd-ctrl-alt-"),
    "SUPER+SHIFT":     (["left_option", "shift"],                      ["left_command", "left_control", "left_option", "left_shift"], "cmd-ctrl-alt-shift-"),
    "ALT":             (["right_command"],                             ["left_control", "left_option", "left_shift"], "ctrl-alt-shift-"),
    "SUPER+ALT":       (["left_option", "right_command"],              ["left_command", "left_control", "left_shift"], "cmd-ctrl-shift-"),
    "SUPER+ALT+SHIFT": (["left_option", "right_command", "shift"],     ["left_command", "left_option", "left_shift"], "cmd-alt-shift-"),
}

WS = [("1", "a"), ("2", "s"), ("3", "d"), ("4", "f"), ("5", "q"), ("6", "w"),
      ("7", "e"), ("8", "r"), ("9", "z"), ("10", "x"), ("11", "c"), ("12", "v")]
DIRS = {"h": "left", "j": "down", "k": "up", "l": "right"}
RESIZE = {"h": "width -50", "l": "width +50", "k": "height -50", "j": "height +50"}
KITTY = "/Applications/kitty.app/Contents/MacOS/kitty --single-instance"

# (class, karabiner key_code, aerospace key, aerospace command(s))
BINDS = [
    ("SUPER", "return_or_enter", "enter", f"exec-and-forget {KITTY}"),
    ("SUPER", "b", "b", 'exec-and-forget open -na "Brave Browser" --args --new-window'),
    ("SUPER", "e", "e", "exec-and-forget open -a Finder"),
    # cmd None: no AeroSpace bind, the emitted combo goes to the app (Raycast hotkey set to ⌃⌥⌘D, toggles)
    ("SUPER", "d", "d", None),
    ("SUPER+SHIFT", "q", "q", "close"),
    ("SUPER", "f", "f", "fullscreen"),
    ("SUPER", "v", "v", "layout floating tiling"),
    ("SUPER", "x", "x", "layout tiles horizontal vertical"),
]
for k, d in DIRS.items():
    BINDS.append(("SUPER", k, k, f"focus {d}"))
    BINDS.append(("SUPER+ALT", k, k, f"move {d}"))
    BINDS.append(("SUPER+ALT+SHIFT", k, k, f"resize {RESIZE[k]}"))
for i, k in WS:
    BINDS.append(("ALT", k, k, f"workspace {i}"))
    BINDS.append(("SUPER+ALT", k, k, f"move-node-to-workspace {i}"))

# kitty only: right Cmd + key -> plain Alt+key for zellij (config/zellij/config.kdl "Alt x" binds).
# Not 'f' (workspace key). Shift is not allowed, so Alt+Shift combos never match.
KITTY_KEYS = ["h", "j", "k", "l", "i", "n", "o", "left_arrow", "down_arrow", "up_arrow", "right_arrow",
              "hyphen", "equal_sign", "open_bracket", "close_bracket"]
KITTY_COND = [{"type": "frontmost_application_if", "bundle_identifiers": [r"^net\.kovidgoyal\.kitty$"]}]


def rules():
    shift = {
        "description": "Right Shift: tap alone = Escape, held = Shift (plain pass-through while right Command or left Option is held, so no Esc inside a layer)",
        "manipulators": [
            {"type": "basic", "from": {"key_code": "right_shift", "modifiers": {"mandatory": [m], "optional": ["any"]}},
             "to": [{"key_code": "right_shift"}]} for m in ("right_command", "left_option")
        ] + [{"type": "basic", "from": {"key_code": "right_shift", "modifiers": {"optional": ["any"]}},
              "to": [{"key_code": "right_shift", "lazy": True}], "to_if_alone": [{"key_code": "escape"}]}],
    }
    kitty = {
        "description": "kitty only: right Command + key = plain Alt+key for zellij (before the ALT rules)",
        "manipulators": [
            {"type": "basic", "from": {"key_code": k, "modifiers": {"mandatory": ["right_command"]}},
             "to": [{"key_code": k, "modifiers": ["left_option"]}], "conditions": KITTY_COND} for k in KITTY_KEYS],
    }
    layers = {
        "description": "Hyprland binds: left Option = SUPER, right Command = ALT (generated by generate.py; see AGENTS.md)",
        "manipulators": [
            {"type": "basic", "from": {"key_code": key, "modifiers": {"mandatory": CLASSES[c][0]}},
             "to": [{"key_code": key, "modifiers": CLASSES[c][1]}]} for c, key, _, _ in BINDS],
    }
    raycast = {
        "description": "Left Command + Space = Raycast (sends its hotkey ⌃⌥⌘D, same as SUPER+D; Spotlight never sees it)",
        "manipulators": [
            {"type": "basic", "from": {"key_code": "spacebar", "modifiers": {"mandatory": ["left_command"]}},
             "to": [{"key_code": "d", "modifiers": CLASSES["SUPER"][1]}]}],
    }
    # Corne layer 1 (MO(1), left thumb next to Space = left Command here): hjkl = arrows. Shift / Option /
    # Control pass through (selection, word jumps); left Command itself is dropped from the output.
    arrows = {
        "description": "Left Command + h/j/k/l = arrow keys (Corne layer 1)",
        "manipulators": [
            {"type": "basic", "from": {"key_code": k, "modifiers": {"mandatory": ["left_command"], "optional": ["shift", "option", "control"]}},
             "to": [{"key_code": a}]} for k, a in (("h", "left_arrow"), ("j", "down_arrow"), ("k", "up_arrow"), ("l", "right_arrow"))],
    }
    return [shift, kitty, layers, raycast, arrows]


def aerospace():
    out = []
    for c, _, akey, cmd in BINDS:
        if cmd is None:
            continue
        out.append(f"    {CLASSES[c][2]}{akey} = '{cmd}'")
    return out


if __name__ == "__main__":
    if "--aerospace" in sys.argv:
        print("\n".join(aerospace()))
        sys.exit()
    cfg = {"profiles": [{
        "complex_modifications": {"rules": rules()},
        "name": "Default profile",
        "selected": True,
        # Kept here: Karabiner saves the keyboard type into this file, and a regenerate would drop it (popup)
        "virtual_hid_keyboard": {"keyboard_type_v2": "iso"},  # Czech internal MacBook keyboard = ISO
        "simple_modifications": [{"from": {"key_code": "caps_lock"}, "to": [{"key_code": "left_control"}]}],
    }]}
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "karabiner.json")
    with open(path, "w") as f:
        json.dump(cfg, f, indent=4)
        f.write("\n")
